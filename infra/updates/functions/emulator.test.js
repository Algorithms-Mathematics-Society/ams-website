import test from 'node:test';
import assert from 'node:assert/strict';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
const projectId = 'demo-ams-updates';
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Run only via the Firebase emulator');
initializeApp({ projectId });
const db = getFirestore();
const endpoint = `http://127.0.0.1:5001/${projectId}/asia-south1/subscribeToUpdates`;
const payload = { name: 'Test visitor', email: 'test@example.test', topic: 'derive', consent: true, consentVersion: '2026-11-01', website: '' };
const send = (data, origin = 'http://localhost:3100') => fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(data) });
test('real HTTP and Firestore: private storage, duplicates, consent, origins, quota', async () => {
  assert.equal((await send(payload, 'https://example.test')).status, 403);
  assert.equal((await send({ ...payload, consent: false })).status, 400);
  assert.equal((await send({ ...payload, website: 'spam' })).status, 400);
  const response = await send(payload);
  assert.equal(response.status, 200); assert.equal((await response.json()).status, 'saved');
  const repeat = await Promise.all(Array.from({ length: 4 }, () => send({ ...payload, topic: 'both' })));
  assert.ok(repeat.every(r => r.status === 200));
  const subscribers = await db.collection('updateSubscribers').get();
  assert.equal(subscribers.size, 1);
  assert.deepEqual(subscribers.docs[0].data().topics, ['derive']);
  assert.equal(subscribers.docs[0].data().emailVerified, false);
  const throttled = await send(payload);
  assert.equal(throttled.status, 429);
  assert.ok(Number(throttled.headers.get("Retry-After")) >= 1);
  assert.ok(Number(throttled.headers.get("Retry-After")) <= 60);
  const publicRead = await fetch(`http://${process.env.FIRESTORE_EMULATOR_HOST}/v1/projects/${projectId}/databases/(default)/documents/updateSubscribers`);
  assert.equal(publicRead.status, 403);
  await db.terminate();
});
